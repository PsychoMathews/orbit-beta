const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('orbit', {
  onEvent: (fn) => ipcRenderer.on('orbit-event', (_e, ev) => fn(ev)),
  onConfig: (fn) => ipcRenderer.on('config', (_e, cfg) => fn(cfg)),
  onGoto: (fn) => ipcRenderer.on('goto', (_e, page) => fn(page)),
  onPreview: (fn) => ipcRenderer.on('preview', (_e, kind) => fn(kind)),
  onTheme: (fn) => { ipcRenderer.on('theme', (_e, t) => fn(t)); ipcRenderer.invoke('theme').then(fn); },
  interactive: (on) => ipcRenderer.send('interactive', on),
  focus: (on) => ipcRenderer.send('focus', on),
  menu: () => ipcRenderer.send('menu'),
  expanded: (open) => ipcRenderer.send('expanded', open),
  onEscape: (fn) => ipcRenderer.on('escape', () => fn()),
  openSettings: (page) => ipcRenderer.send('open-settings', page),
  openUrl: (url) => ipcRenderer.send('open-url', url),
  get: (p) => ipcRenderer.invoke('bridge', 'GET', p),
  post: (p, body) => ipcRenderer.invoke('bridge', 'POST', p, body),
  status: () => ipcRenderer.invoke('status'),
  system: () => ipcRenderer.invoke('system'),
  speedTest: () => ipcRenderer.invoke('speedtest'),
  onSpeed: (fn) => ipcRenderer.on('speed', (_e, p) => fn(p)),
  aiUsage: () => ipcRenderer.invoke('ai-usage'),
  clips: () => ipcRenderer.invoke('clips'),
  islandRect: (r) => ipcRenderer.send('island-rect', r),
  downloads: () => ipcRenderer.invoke('downloads'),
  lyrics: (artist, title, duration) => ipcRenderer.invoke('lyrics', artist, title, duration),
  shelf: () => ipcRenderer.invoke('shelf'),
  shelfAdd: (items) => ipcRenderer.send('shelf-add', items),
  shelfRemove: (i) => ipcRenderer.send('shelf-remove', i),
  pathOf: (file) => webUtils.getPathForFile(file),
  fileOpen: (f) => ipcRenderer.send('file-open', f),
  fileShow: (f) => ipcRenderer.send('file-show', f),
  fileDrag: (f) => ipcRenderer.send('file-drag', f),
  copy: (text) => ipcRenderer.send('copy', text),
  clearClips: () => ipcRenderer.send('clips-clear'),
  notesGet: () => ipcRenderer.invoke('notes-get'),
  notesSet: (text) => ipcRenderer.send('notes-set', text),
  configGet: () => ipcRenderer.invoke('config-get'),
  configSet: (next) => ipcRenderer.send('config-set', next),
  configReset: () => ipcRenderer.send('config-reset'),
  configExport: () => ipcRenderer.invoke('config-export'),
  configImport: () => ipcRenderer.invoke('config-import'),
  permissions: () => ipcRenderer.invoke('permissions'),
});
